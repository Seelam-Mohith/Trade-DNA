function seeded(seed) {
  let s = seed
  return function () {
    s = (s * 16807) % 2147483647
    return (s - 1) / 2147483646
  }
}

function buildSeries(seed, points, base, drift, vol) {
  const rand = seeded(seed)
  let value = base
  const out = []
  for (let i = 0; i < points; i++) {
    value = value * (1 + (rand() - 0.48) * drift) * (1 + (rand() - 0.5) * vol * 0.1)
    out.push({
      date: `2025-${String(((i / points) * 12) % 12 + 1).padStart(2, '0')}`,
      close: Number(value.toFixed(2)),
    })
  }
  return out
}

